-- Orders + PayPal checkout: changes on top of the existing orders / order_items tables.
-- Safe to re-run. Run in Supabase Dashboard → SQL Editor.

-- ---------------------------------------------------------------
-- orders
-- ---------------------------------------------------------------
alter table public.orders
  alter column user_id drop not null,                 -- allow guest checkout
  add column if not exists order_number bigint generated always as identity,
  add column if not exists customer_name text,
  add column if not exists email text,
  add column if not exists phone text,
  add column if not exists shipping_address text,
  add column if not exists currency text not null default 'PHP',
  add column if not exists paypal_order_id text,
  add column if not exists paypal_capture_id text,
  add column if not exists paid_at timestamptz;

create unique index if not exists orders_order_number_key on public.orders (order_number);
create unique index if not exists orders_paypal_order_id_key on public.orders (paypal_order_id);

-- ---------------------------------------------------------------
-- order_items
-- ---------------------------------------------------------------
alter table public.order_items
  add column if not exists product_name text,
  add column if not exists size text;

-- Make sure order_items.id fills itself in (no-op if it already has a default/identity).
do $$
begin
  if exists (
    select 1 from information_schema.columns
     where table_schema = 'public' and table_name = 'order_items' and column_name = 'id'
       and is_identity = 'NO' and column_default is null
  ) then
    alter table public.order_items alter column id add generated by default as identity;
  end if;
end $$;

create index if not exists order_items_order_id_idx on public.order_items (order_id);

-- ---------------------------------------------------------------
-- Row Level Security
-- Orders are written only by the server (secret key bypasses RLS).
-- Logged-in customers may read their own orders.
-- ---------------------------------------------------------------
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "Customers read own orders" on public.orders;
create policy "Customers read own orders" on public.orders
  for select to authenticated
  using (user_id = auth.uid());

drop policy if exists "Customers read own order items" on public.order_items;
create policy "Customers read own order items" on public.order_items
  for select to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = order_items.order_id and o.user_id = auth.uid()
  ));

-- ---------------------------------------------------------------
-- mark_order_paid: flips a pending order to paid and reduces stock
-- in one transaction. Server-only (service_role).
-- ---------------------------------------------------------------
drop function if exists public.mark_order_paid(uuid, text);

create function public.mark_order_paid(p_order_id uuid, p_capture_id text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  update orders
     set status = 'paid', paypal_capture_id = p_capture_id, paid_at = now()
   where id = p_order_id and status = 'pending';

  if not found then
    return false; -- already paid or not found
  end if;

  update products p
     set stock = greatest(p.stock - oi.qty, 0)
    from (
      select product_id, sum(quantity) as qty
        from order_items
       where order_id = p_order_id
       group by product_id
    ) oi
   where p.id = oi.product_id;

  return true;
end;
$$;

revoke execute on function public.mark_order_paid(uuid, text) from public, anon, authenticated;
grant execute on function public.mark_order_paid(uuid, text) to service_role;
